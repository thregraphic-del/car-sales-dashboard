-- «انضم لفريقنا»: team members with a referral code, who signed up with it, what they earned
-- and their payout requests. Money is in halalas (1 riyal = 100). Nothing runs in the background.
CREATE TABLE IF NOT EXISTS team_members (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    INTEGER NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
  name       TEXT NOT NULL,
  email      TEXT NOT NULL,
  phone      TEXT NOT NULL,
  code       TEXT NOT NULL UNIQUE,
  created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS referrals (
  id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  member_id        INTEGER NOT NULL REFERENCES team_members(id) ON DELETE CASCADE,
  referred_user_id INTEGER NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
  created_at       TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS referrals_member ON referrals (member_id);
CREATE TABLE IF NOT EXISTS team_credits (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  member_id    INTEGER NOT NULL REFERENCES team_members(id) ON DELETE CASCADE,
  amount_cents INTEGER NOT NULL,
  note         TEXT,
  created_at   TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS team_credits_member ON team_credits (member_id);
CREATE TABLE IF NOT EXISTS payout_requests (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  member_id    INTEGER NOT NULL REFERENCES team_members(id) ON DELETE CASCADE,
  amount_cents INTEGER NOT NULL,
  status       TEXT NOT NULL DEFAULT 'pending',
  note         TEXT,
  seen         INTEGER NOT NULL DEFAULT 0,
  created_at   TEXT NOT NULL,
  decided_at   TEXT
);
CREATE INDEX IF NOT EXISTS payout_requests_member ON payout_requests (member_id, status);
