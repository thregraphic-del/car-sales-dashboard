-- What each AI request cost, and which video it was for (so the owner can see the cost of every clip and every step:
-- translation, summary, words…). One small row per request; nothing runs in the background.
CREATE TABLE IF NOT EXISTS ai_cost_items (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  source_id  INTEGER REFERENCES sources(id) ON DELETE SET NULL,
  req_id     TEXT,
  task       TEXT    NOT NULL,
  day        TEXT    NOT NULL,
  prompt_tokens     INTEGER NOT NULL DEFAULT 0,
  completion_tokens INTEGER NOT NULL DEFAULT 0,
  cost       DOUBLE PRECISION NOT NULL DEFAULT 0,
  transcripts INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS ai_cost_items_user_day ON ai_cost_items (user_id, day);
CREATE INDEX IF NOT EXISTS ai_cost_items_user_source ON ai_cost_items (user_id, source_id);
CREATE INDEX IF NOT EXISTS ai_cost_items_req ON ai_cost_items (req_id);
